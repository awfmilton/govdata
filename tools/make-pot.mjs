/**
 * Minimal POT generator for the PublicTech themes/plugin.
 *
 * WordPress's canonical tool is `wp i18n make-pot`, which isn't available in
 * every environment, so this is a lightweight stand-in that scans PHP for the
 * common gettext calls and emits one .pot per text domain. It handles the
 * single-line 2-arg family (__/_e/esc_html__/esc_attr__/esc_html_e/esc_attr_e)
 * and _x (with context). Multi-line calls, plurals (_n) and concatenated
 * strings are NOT extracted — run `wp i18n make-pot` for a complete catalog.
 *
 * Usage: npm run pot   (or: node tools/make-pot.mjs)
 */
import { readdirSync, statSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';

const DOMAINS = {
	'publictech-core':     { root: 'publictech-core',     out: 'publictech-core/languages/publictech-core.pot' },
	'publictech-terminal': { root: 'publictech-terminal', out: 'publictech-terminal/languages/publictech-terminal.pot' },
	'publictech-mcp':      { root: 'publictech-mcp',       out: 'publictech-mcp/languages/publictech-mcp.pot' },
};

function* phpFiles( dir ) {
	let entries;
	try { entries = readdirSync( dir ); } catch { return; }
	for ( const e of entries ) {
		if ( e === 'vendor' || e === 'node_modules' || e === 'languages' ) continue;
		const p = join( dir, e );
		if ( statSync( p ).isDirectory() ) yield* phpFiles( p );
		else if ( e.endsWith( '.php' ) ) yield p;
	}
}

const STR     = "(?:'((?:[^'\\\\]|\\\\.)*)'|\"((?:[^\"\\\\]|\\\\.)*)\")";
const RE_2ARG = new RegExp( `(?:__|_e|esc_html__|esc_attr__|esc_html_e|esc_attr_e)\\(\\s*${ STR }\\s*,\\s*${ STR }\\s*\\)`, 'g' );
const RE_X    = new RegExp( `_x\\(\\s*${ STR }\\s*,\\s*${ STR }\\s*,\\s*${ STR }\\s*\\)`, 'g' );
const pick    = ( a, b ) => ( a !== undefined ? a : b );

for ( const [ domain, cfg ] of Object.entries( DOMAINS ) ) {
	const entries = new Map(); // key -> { msgid, msgctxt }
	for ( const file of phpFiles( cfg.root ) ) {
		const src = readFileSync( file, 'utf8' );
		let m;
		while ( ( m = RE_2ARG.exec( src ) ) ) {
			const msgid = pick( m[ 1 ], m[ 2 ] );
			if ( pick( m[ 3 ], m[ 4 ] ) === domain && msgid ) entries.set( msgid, { msgid } );
		}
		while ( ( m = RE_X.exec( src ) ) ) {
			const msgid = pick( m[ 1 ], m[ 2 ] );
			const ctx   = pick( m[ 3 ], m[ 4 ] );
			if ( pick( m[ 5 ], m[ 6 ] ) === domain && msgid ) entries.set( ctx + '' + msgid, { msgid, msgctxt: ctx } );
		}
	}

	const header =
`# Translation template for ${ domain }.
# Generated by tools/make-pot.mjs — for a complete catalog use \`wp i18n make-pot\`.
msgid ""
msgstr ""
"Project-Id-Version: ${ domain }\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"X-Domain: ${ domain }\\n"
`;
	const body = [ ...entries.values() ]
		.sort( ( a, b ) => a.msgid.localeCompare( b.msgid ) )
		.map( ( e ) => {
			const id  = e.msgid.replace( /\\/g, '\\\\' ).replace( /"/g, '\\"' );
			const ctx = e.msgctxt ? `msgctxt "${ e.msgctxt.replace( /"/g, '\\"' ) }"\n` : '';
			return `${ ctx }msgid "${ id }"\nmsgstr ""\n`;
		} )
		.join( '\n' );

	mkdirSync( dirname( cfg.out ), { recursive: true } );
	writeFileSync( cfg.out, header + '\n' + body );
	console.log( `${ domain }: ${ entries.size } strings -> ${ cfg.out }` );
}
